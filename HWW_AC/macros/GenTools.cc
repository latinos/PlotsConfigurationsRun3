//-> Order the index by pt

std::vector<int> pTorder(std::vector<int> old_Idx, RVecF LHEPart_pt){

  std::vector<int> order(old_Idx.size(), 0);

  for(size_t i = 0; i < old_Idx.size(); ++i){
    int Idxi = old_Idx[i];
    for(size_t j = 0; j < old_Idx.size(); ++j){
      int Idxj = old_Idx[j];
      if(Idxi == Idxj) continue;
      if(LHEPart_pt[Idxi] > LHEPart_pt[Idxj]) order[i]++;
      if(LHEPart_pt[Idxi] == LHEPart_pt[Idxj] && i < j) order[j]++;
    }
  }

  std::vector<int> new_Idx(old_Idx.size());
  for(size_t i = 0; i < old_Idx.size(); ++i){
    new_Idx[order[i]] = old_Idx[i];
  }

  return new_Idx;
}

//-> Find LHE particles (higher precision) with closest match to GenParticles : LHE <Idx, (pt, eta, phi, Id)>

std::map<int, std::vector<float>> getLHE(std::vector<int>& GenPart_Idx, RVecF GenPart_pt, RVecF GenPart_eta, RVecF GenPart_phi, RVecI GenPart_pdgId, int nLHEPart, RVecF LHEPart_pt, RVecF LHEPart_eta, RVecF LHEPart_phi, RVecI LHEPart_status, RVecI LHEPart_pdgId, string dec){ 
    
  std::map<int, std::vector<float>> pLHE; 
  for(int idxG : GenPart_Idx){
     
    float pt  = GenPart_pt[idxG];
    float eta = GenPart_eta[idxG];
    float phi = GenPart_phi[idxG];
    int pdgid = GenPart_pdgId[idxG]; 
      
    float deltaR = 9999.0;
    int LHEidx = -1;
    float LHEpt = 0, LHEeta = 0, LHEphi = 0;
    int LHEpdg = 0;

    for(int il = 0; il < nLHEPart; ++il) {
      if(LHEPart_status[il] != 1) continue;
      if(LHEPart_pdgId[il] != pdgid) continue;

      float dphi = phi - LHEPart_phi[il];
      if(dphi > M_PI) dphi -= 2 * M_PI;
      if(dphi < -M_PI) dphi += 2 * M_PI;

      float deta = eta - LHEPart_eta[il];
      float dR = std::sqrt(deta * deta + dphi * dphi);

      if(deltaR > dR){
	deltaR = dR;
	LHEidx = il; 
	LHEpt  = LHEPart_pt[il];
	LHEeta = LHEPart_eta[il];
	LHEphi = LHEPart_phi[il];
	LHEpdg = LHEPart_pdgId[il];
      }
    }
      
    if(LHEidx == -1){ // VERY rare, use placeholder key value
      int key = pdgid + 100 * (pLHE.size() + 1);
      pLHE[key] = {pt, eta, phi, static_cast<float>(pdgid)};
    }else if (dec == "cut" && deltaR > 0.2) { // Use GenPart information if direction is too different
      pLHE[LHEidx] = {pt, eta, phi, static_cast<float>(pdgid)};
    }else{
      pLHE[LHEidx] = {LHEpt, LHEeta, LHEphi, static_cast<float>(pdgid)};
    }
  }
 
  return pLHE;
}

//-> Iterate over mothers to find Higgs

bool FromH(int pi, RVecI GenPart_genPartIdxMother, RVecI GenPart_pdgId){ 
    
  while (GenPart_genPartIdxMother[pi] != -1){
    pi = GenPart_genPartIdxMother[pi];
    if (GenPart_pdgId[pi] == 25) return true;
  }	
  return false;
}

//-> Remove rare additonal hadrons 

std::vector<int> RemoveAddHadron(std::vector<int> GenPart_Idx, RVecI GenPart_genPartIdxMother){ 
    
  std::vector<int> remove_Idx;
  for(unsigned i1 = 0; i1 < GenPart_Idx.size(); i1++){
    int idx1 = GenPart_Idx[i1];
    int idxM = GenPart_genPartIdxMother[idx1];
    int NumWithThisIdx = 0;
    for(unsigned i2 = 0; i2 < GenPart_Idx.size(); i2++){
      int idx2 = GenPart_Idx[i2]; 
      if (GenPart_genPartIdxMother[idx2] == idxM) NumWithThisIdx += 1;
    } 
    if (NumWithThisIdx == 2) continue;
    for(unsigned i2 = 0; i2 < GenPart_Idx.size(); i2++){
      int idx2 = GenPart_Idx[i2];
      if (GenPart_genPartIdxMother[idx2] == idxM && (std::find(remove_Idx.begin(), remove_Idx.end(), idx2) == remove_Idx.end())) remove_Idx.push_back(idx2);   
    }
  }

  for(int rem : remove_Idx){
    GenPart_Idx.erase(std::remove(GenPart_Idx.begin(), GenPart_Idx.end(), rem), GenPart_Idx.end());
  }
    
  return GenPart_Idx;  
}

//-> Remove W -> gamma W -> e+ e- W                              
std::vector<int> RemoveGammaW(std::vector<int> GenPart_Idx, RVecI GenPart_pdgId, RVecI GenPart_genPartIdxMother){ 
    
  std::vector<int> remove_Idx;
  for(unsigned i1 = 0; i1 < GenPart_Idx.size(); i1++){ 
    int idx1 = GenPart_Idx[i1];
    for(unsigned i2 = 0; i2 < GenPart_Idx.size(); i2++){
      int idx2 = GenPart_Idx[i2]; 
      if(i1 >= i2) continue;  
      if(GenPart_genPartIdxMother[idx1] != GenPart_genPartIdxMother[idx2]) continue;
      if(GenPart_pdgId[idx1] + GenPart_pdgId[idx2] == 0){
	if(std::find(remove_Idx.begin(), remove_Idx.end(), idx1) == remove_Idx.end()) remove_Idx.push_back(idx1);
	if(std::find(remove_Idx.begin(), remove_Idx.end(), idx2) == remove_Idx.end()) remove_Idx.push_back(idx2);
      }
    }
  }
    
  for(int rem : remove_Idx){
    GenPart_Idx.erase(std::remove(GenPart_Idx.begin(), GenPart_Idx.end(), rem), GenPart_Idx.end());
  } 
    
  return GenPart_Idx;
}

